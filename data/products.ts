type Draft = Omit<Product, "currency" | "price" | "compareAtPrice" | "seoTitle" | "seoDescription"> &
  Partial<Pick<Product, "seoTitle" | "seoDescription">>;

function make(d: Draft): Product {
  const primaryType = d.variants[0]?.type;
  const priced = d.variants.filter((v) => v.type === primaryType && !v.quoteOnly && v.available);
  const cheapest = priced.reduce<Variant | undefined>(
    (best, v) => (!best || v.price < best.price ? v : best),
    undefined
  );
  const trade = d.bulkAvailable ? bulkDefaults[d.category] : undefined;

  return {
    currency: "INR",
    price: cheapest?.price ?? 0,
    compareAtPrice: cheapest?.compareAtPrice,
    seoTitle: `${d.name} | Buy Online | Gomay`,
    seoDescription: d.shortDescription,
    ...trade,
    ...d,
  };
}

