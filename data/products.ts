/* --------------------------- selectors / lookups --------------------------- */

export const getProductBySlug = (slug: string): Product | undefined =>
  products.find((p) => p.slug === slug);

export const retailProducts = (): Product[] => products.filter((p) => p.retailAvailable);
export const corporateProducts = (): Product[] => products.filter((p) => p.corporateAvailable);
export const bulkProducts = (): Product[] => products.filter((p) => p.bulkAvailable);
export const bestsellers = (): Product[] => products.filter((p) => p.bestseller);
export const festiveProducts = (): Product[] => products.filter((p) => p.festive);
export const newProducts = (): Product[] => products.filter((p) => p.isNew);

export const productsByCategory = (slug: string): Product[] =>
  products.filter((p) => p.category === slug);

export const productsByCollection = (slug: string): Product[] =>
  products.filter((p) => p.collections.includes(slug as Product["collections"][number]));

export const productsByPurpose = (slug: string): Product[] =>
  products.filter((p) => p.purposes.includes(slug as Product["purposes"][number]));

export function relatedProducts(product: Product, limit = 4): Product[] {
  const sameCategory = products.filter((p) => p.id !== product.id && p.category === product.category);
  const sharedPurpose = products.filter(
    (p) => p.id !== product.id && p.category !== product.category && p.purposes.some((u) => product.purposes.includes(u))
  );
  return [...sameCategory, ...sharedPurpose].slice(0, limit);
}

export function frequentlyBoughtTogether(product: Product, limit = 3): Product[] {
  const pool = products.filter((p) => p.id !== product.id && p.retailAvailable && p.price <= 1500);
  const sameUse = pool.filter((p) => p.purposes.some((u) => product.purposes.includes(u)));
  const rest = pool.filter((p) => !sameUse.includes(p));
  return [...sameUse, ...rest].slice(0, limit);
}

/** Distinct pack labels across the catalogue — used to build shop filters. */
export const allPackLabels = (): string[] =>
  Array.from(new Set(products.flatMap((p) => p.variants.filter((v) => v.type === "pack").map((v) => v.label))));

export const allWeightLabels = (): string[] =>
  Array.from(new Set(products.flatMap((p) => p.variants.filter((v) => v.type === "weight").map((v) => v.label))));

export const priceBounds = (): { min: number; max: number } => {
  const prices = products.filter((p) => p.price > 0).map((p) => p.price);
  return { min: Math.min(...prices), max: Math.max(...prices) };
};
